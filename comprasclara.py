import json
import os
import pandas as pd
from pyspark.sql import SparkSession
from pyspark.sql.functions import col, trim, upper


def processar_silver_catalogo(
    caminho_bronze: str = "datalake/bronze/compras_brutas_completo.json",
    caminho_silver: str = "datalake/silver/catmat_grupos",
):
    if not os.path.exists(caminho_bronze):
        raise FileNotFoundError(f"Arquivo Bronze não encontrado: {caminho_bronze}")

    with open(caminho_bronze, "r", encoding="utf-8") as f:
        conteudo = json.load(f)

    if isinstance(conteudo, dict):
        registros = conteudo.get("resultado", [])
    elif isinstance(conteudo, list):
        registros = conteudo
    else:
        registros = []

    if not registros:
        raise ValueError("Nenhum registro encontrado para processar na Camada Silver.")

    spark = (
        SparkSession.builder
        .appName("CompraClara-Silver")
        .getOrCreate()
    )

    # Conversão via Pandas com astype(str) para evitar falha de inferência de esquema no Spark
    pdf = pd.DataFrame(registros).astype(str)
    df = spark.createDataFrame(pdf)

    # Padroniza código do item e descarta colunas de descrição/nomeGrupo
    colunas_para_remover_desc = [
        c for c in df.columns
        if c.lower() in {"nomegrupo", "descricao_item", "descricaoitem"}
    ]
    if colunas_para_remover_desc:
        df = df.drop(*colunas_para_remover_desc)

    col_codigo = next(
        (c for c in df.columns if c.lower() in {"codigogrupo", "codigo_item", "codigoitem"}),
        None,
    )
    if col_codigo:
        df = df.withColumn("codigo_item", upper(trim(col(col_codigo))))
        if col_codigo != "codigo_item":
            df = df.drop(col_codigo)

    # Limpa strings inválidas/nulas em todas as colunas restantes
    valores_invalidos = ["", "NONE", "NAN", "NULL", "N/A"]
    for c in df.columns:
        df = df.withColumn(c, trim(col(c)))
        df = df.filter(
            col(c).isNotNull() & (~upper(col(c)).isin(valores_invalidos))
        )

    # Remove duplicatas após padronização
    df_silver = df.dropDuplicates()

    # Gravação em Parquet com sobrescrita explícita
    pasta_silver = os.path.dirname(caminho_silver)
    if pasta_silver:
        os.makedirs(pasta_silver, exist_ok=True)

    df_silver.write.mode("overwrite").parquet(caminho_silver)

    print(
        f"Silver concluída! {df_silver.count()} registros salvos em Parquet em: "
        f"{caminho_silver}"
    )
    df_silver.printSchema()
    df_silver.show(10, truncate=False)

    return df_silver



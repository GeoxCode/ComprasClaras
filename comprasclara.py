def processar_silver_catalogo(
    caminho_bronze_json: str,
    caminho_silver_parquet: str,
) -> None:
    if not os.path.exists(caminho_bronze_json):
        raise FileNotFoundError(f"Arquivo Bronze não encontrado: {caminho_bronze_json}")

    with open(caminho_bronze_json, "r", encoding="utf-8") as f:
        payload = json.load(f)

    if isinstance(payload, dict) and isinstance(payload.get("resultado"), list):
        registros = payload["resultado"]
    elif isinstance(payload, list):
        registros = payload
    else:
        registros = []

    if not registros:
        print(f"Nenhum registro encontrado em {caminho_bronze_json} para processar na Silver.")
        return

    # Converte via Pandas e aplica astype(str) para evitar ambiguidade de esquema no Spark
    pdf = pd.DataFrame(registros).astype(str)

    spark = SparkSession.builder.appName("CompraClara-SilverPipeline").getOrCreate()
    df_raw = spark.createDataFrame(pdf)

    # Detecta colunas reais mais comuns nos endpoints de catálogo (ex.: codigoGrupo/descricaoGrupo)
    colunas = set(df_raw.columns)

    col_codigo = next(
        (c for c in ["codigoGrupo", "codigoItem", "codigoServico", "id_item"] if c in colunas),
        None,
    )
    col_descricao = next(
        (
            c
            for c in [
                "descricaoGrupo",
                "descricaoItem",
                "descricaoServico",
                "nome_item",
            ]
            if c in colunas
        ),
        None,
    )

    df_silver = df_raw

    # Limpa strings "None", "nan" ou vazias geradas após astype(str)
    for c in df_silver.columns:
        df_silver = df_silver.withColumn(c, trim(col(c)))

    if col_codigo:
        df_silver = df_silver.filter(
            col(col_codigo).isNotNull()
            & (col(col_codigo) != "")
            & (~upper(col(col_codigo)).isin("NONE", "NAN", "NULL"))
        ).withColumn("codigo_item", upper(col(col_codigo)))

    if col_descricao:
        df_silver = df_silver.filter(
            col(col_descricao).isNotNull()
            & (col(col_descricao) != "")
            & (~upper(col(col_descricao)).isin("NONE", "NAN", "NULL"))
        ).withColumn("descricao_item", upper(trim(col(col_descricao))))

    df_silver = df_silver.dropDuplicates()

    os.makedirs(os.path.dirname(caminho_silver_parquet), exist_ok=True)
    df_silver.write.mode("overwrite").parquet(caminho_silver_parquet)

    print(f"Camada Silver gravada em Parquet: {caminho_silver_parquet}")
    df_silver.show(10, truncate=False)



def coletar_bronze_secoes_servico(
    url_base: str = "https://dadosabertos.compras.gov.br/modulo-servico/1_consultarSecaoServico",
    caminho_bronze: str = "datalake/bronze/secoes_servico_brutos.json",
    tamanho_pagina: int = 100,
    max_paginas: int | None = 10,
    timeout_seg: int = 30,
    pausa_seg: float = 0.2,
) -> list:
    pasta = os.path.dirname(caminho_bronze)
    if pasta:
        os.makedirs(pasta, exist_ok=True)

    headers = {
        "Accept": "application/json",
        "User-Agent": "Mozilla/5.0",
    }

    pagina = 1
    todos_os_registros = []

    print("=== Iniciando coleta paginada de Seções de Serviço (Camada Bronze) ===")

    while True:
        if max_paginas is not None and pagina > max_paginas:
            print(f"Limite de páginas atingido ({max_paginas}).")
            break

        url_atual = f"{url_base}?pagina={pagina}&tamanhoPagina={tamanho_pagina}"

        try:
            response = requests.get(url_atual, headers=headers, timeout=timeout_seg)

            if response.status_code == 200:
                dados = response.json()

                if isinstance(dados, dict):
                    if "resultado" in dados and isinstance(dados["resultado"], list):
                        lista_pagina = dados["resultado"]
                    else:
                        chave_lista = next(
                            (k for k, v in dados.items() if isinstance(v, list)), None
                        )
                        lista_pagina = dados[chave_lista] if chave_lista else []
                elif isinstance(dados, list):
                    lista_pagina = dados
                else:
                    lista_pagina = []

                if not lista_pagina:
                    print(f"Fim dos dados atingido na página {pagina}.")
                    break

                todos_os_registros.extend(lista_pagina)
                print(
                    f"Página {pagina} coletada ({len(lista_pagina)} registros). "
                    f"Total acumulado: {len(todos_os_registros)}"
                )
                pagina += 1

                if pausa_seg > 0:
                    time.sleep(pausa_seg)
            else:
                print(
                    f"Aviso: API respondeu com código HTTP {response.status_code} "
                    f"na página {pagina}."
                )
                break

        except Exception as erro:
            print(f"Erro na requisição da página {pagina}: {erro}")
            break

    payload_final = {
        "total_registros": len(todos_os_registros),
        "resultado": todos_os_registros,
    }

    with open(caminho_bronze, "w", encoding="utf-8") as f:
        json.dump(payload_final, f, ensure_ascii=False, indent=4)

    print(
        f"Bronze de seções de serviço concluída! {len(todos_os_registros)} registros "
        f"salvos em: {caminho_bronze}"
    )
    return todos_os_registros



url_base_servico = "https://dadosabertos.compras.gov.br/modulo-servico/1_consultarGrupoServico"
headers = {
    "Accept": "application/json",
    "User-Agent": "Mozilla/5.0"
}

pagina = 1
tamanho_pagina = 100
todos_os_servicos = []

while True:
    url_atual = f"{url_base_servico}?pagina={pagina}&tamanhoPagina={tamanho_pagina}"
    try:
        response = requests.get(url_atual, headers=headers)
        if response.status_code == 200:
            dados = response.json()

            if isinstance(dados, dict):
                if "resultado" in dados:
                    lista_pagina = dados["resultado"]
                else:
                    chave_lista = next((k for k, v in dados.items() if isinstance(v, list)), None)
                    lista_pagina = dados[chave_lista] if chave_lista else []
            elif isinstance(dados, list):
                lista_pagina = dados
            else:
                lista_pagina = []

            if not lista_pagina:
                print(f"Fim dos dados de serviços atingido na página {pagina}.")
                break

            todos_os_servicos.extend(lista_pagina)
            print(f"Serviços - Página {pagina} recolhida ({len(lista_pagina)} registos). Total acumulado: {len(todos_os_servicos)}")
            pagina += 1
        else:
            print(f"Aviso: A API de serviços respondeu com o código {response.status_code} na página {pagina}")
            break
    except Exception as e:
        print(f"Ocorreu um erro na requisição de serviços na página {pagina}:", e)
        break

caminho_bronze_servico = "datalake/bronze/servicos_brutos.json"
payload_servicos = {
    "total_registros": len(todos_os_servicos),
    "resultado": todos_os_servicos
}

with open(caminho_bronze_servico, "w", encoding="utf-8") as f:
    json.dump(payload_servicos, f, ensure_ascii=False, indent=4)

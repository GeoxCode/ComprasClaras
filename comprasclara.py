# Padroniza o texto para facilitar a pesquisa.
# Remove diferenças entre maiúsculas, minúsculas e acentos.

def normalizar_texto(texto):

    texto = str(texto or "").strip().casefold()

    texto = unicodedata.normalize("NFD", texto)

    texto = "".join(
        caractere for caractere in texto
        if unicodedata.category(caractere) != "Mn"
    )

    return " ".join(texto.split())


# Formata os preços para o padrão brasileiro.

def formatar_preco(valor):

    try:
        valor = float(valor)

        return (
            f"R$ {valor:,.2f}"
            .replace(",", "X")
            .replace(".", ",")
            .replace("X", ".")
        )

    except (TypeError, ValueError):
        return "Não informado"


# ==========================================
# 3. MECANISMO DE BUSCA
# ==========================================

def pesquisar_item(texto):

    termo = normalizar_texto(texto)

    # Impede uma pesquisa vazia.
    if not termo:
        return (
            [],
            "Digite o nome ou código do item para pesquisar."
        )

    resultados = []

    # Percorre os registros disponíveis.
    for registro in registros_teste:

        nome = normalizar_texto(
            registro.get("descricao_contrato", "")
        )

        codigo = normalizar_texto(
            registro.get("codigo_item", "")
        )

        # Procura pelo nome ou código do item.
        if termo in nome or termo in codigo:

            resultados.append([
                registro.get(
                    "descricao_contrato",
                    "Não informado"
                ),
                formatar_preco(
                    registro.get("preco_unitario")
                ),
                registro.get(
                    "orgao",
                    "Não informado"
                )
            ])

    # Mensagem quando existem resultados.
    if resultados:

        mensagem = (
            f"**{len(resultados)} registro(s) encontrado(s).** "
            "Dados de demonstração."
        )

    # Mensagem quando não existem resultados.
    else:

        mensagem = (
            f"Nenhum item encontrado para **{texto.strip()}** "
            "nos dados de demonstração."
        )

    return resultados, mensagem



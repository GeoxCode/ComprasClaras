produtos = {
    "351109 - Peça/acessório - Transformador": [248, 252, 255, 260, 265, 270, 262, 690],
    "384044 - Cartucho toner impressora Lexmark": [185, 190, 195, 200, 205, 210, 198, 490],
    "395849 - Modelo anatômico para fins didáticos": [430, 440, 450, 465, 480, 455, 470, 1150],
    "456018 - Conector uso médico": [12.80, 13.20, 13.50, 14, 14.20, 15, 13.80, 48],
    "458474 - Cabo elétrico isolado": [8.80, 9.20, 9.80, 10.50, 11, 11.40, 10.20, 38]
}

def analisar(produto):
    precos = produtos[produto]
    mediana = pd.Series(precos).median()

    dados = pd.DataFrame({
        "Pesquisa": [f"Pesquisa {i}" for i in range(1, 9)],
        "Preço (R$)": precos,
        "Situação": [
            "Possível discrepância" if p > mediana * 1.3
            else "Dentro do padrão"
            for p in precos
        ]
    })

    fig = go.Figure()

    fig.add_trace(go.Bar(
        x=dados["Pesquisa"],
        y=dados["Preço (R$)"],
        name="Preços encontrados"
    ))

    fig.add_hline(
        y=mediana,
        line_dash="dash",
        annotation_text=f"Mediana: R$ {mediana:.2f}"
    )

    fig.update_layout(
        title=f"Comparação de preços - {produto}",
        xaxis_title="Pesquisas",
        yaxis_title="Preço (R$)",
        template="plotly_white"
    )

    discrepantes = dados[dados["Situação"] == "Possível discrepância"]

    if len(discrepantes) > 0:
        alerta = (
            "ALERTA: Foram encontrados possíveis preços discrepantes.\n"
            + discrepantes.to_string(index=False)
        )
    else:
        alerta = "Nenhuma discrepância identificada."

    return fig, dados, alerta



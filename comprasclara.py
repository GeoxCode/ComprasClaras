def processar_gold_anomalias(
    caminho_silver_grupos: str = "datalake/silver/catmat_grupos",
    caminho_gold: str = "datalake/gold/anomalias_precos",
    df_precos_silver: DataFrame | None = None,
    limiar_zscore: float = 2.0,
):
    spark = (
        SparkSession.builder
        .appName("CompraClara-Gold")
        .getOrCreate()
    )

    df_grupos = spark.read.parquet(caminho_silver_grupos)

    # Se ainda não houver tabela Silver de preços/itens detalhados, cria uma base de teste
    # apenas para validar o JOIN e o Z-score no fluxo atual
    if df_precos_silver is None:
        dados_exemplo = [
            ("20", 100.0),
            ("20", 105.0),
            ("20", 98.0),
            ("20", 320.0),  # Anomalia de preço para teste
            ("23", 50.0),
            ("23", 52.0),
            ("23", 49.0),
            ("34", 200.0),
            ("34", 210.0),
        ]
        df_precos_silver = spark.createDataFrame(
            dados_exemplo, ["codigo_item", "preco_unitario"]
        )

    # Garante tipo numérico para o cálculo estatístico e chave padronizada para o JOIN
    df_precos_prep = (
        df_precos_silver
        .withColumn("codigo_item", col("codigo_item").cast("string"))
        .withColumn("preco_unitario", col("preco_unitario").cast("double"))
        .filter(col("codigo_item").isNotNull() & col("preco_unitario").isNotNull())
    )

    df_grupos_prep = (
        df_grupos
        .withColumn("codigo_item", col("codigo_item").cast("string"))
        .filter(col("codigo_item").isNotNull())
    )

    # Cruzamento pelo código do item evitando ambiguidade de colunas
    df_cruzado = df_precos_prep.join(
        df_grupos_prep,
        on="codigo_item",
        how="inner",
    )

    # Janela por codigo_item para calcular média e desvio padrão do grupo/item
    janela_item = Window.partitionBy("codigo_item")

    df_gold = (
        df_cruzado
        .withColumn("media_preco", avg("preco_unitario").over(janela_item))
        .withColumn("desvio_padrao_preco", stddev("preco_unitario").over(janela_item))
        .withColumn(
            "z_score",
            when(
                col("desvio_padrao_preco").isNotNull() & (col("desvio_padrao_preco") > 0),
                (col("preco_unitario") - col("media_preco")) / col("desvio_padrao_preco"),
            ).otherwise(lit(0.0)),
        )
        .withColumn(
            "anomalia_preco",
            spark_abs(col("z_score")) >= lit(limiar_zscore),
        )
    )

    pasta_gold = os.path.dirname(caminho_gold)
    if pasta_gold:
        os.makedirs(pasta_gold, exist_ok=True)

    df_gold.write.mode("overwrite").parquet(caminho_gold)

    print(
        f"Gold concluída! {df_gold.count()} registros salvos em Parquet em: "
        f"{caminho_gold}"
    )
    df_gold.printSchema()
    df_gold.show(20, truncate=False)

    return df_gold


